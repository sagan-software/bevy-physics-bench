import initJolt from 'jolt-physics';
import { validateSettings } from './results';
import type Jolt from 'jolt-physics';
import type { Body, Settings, Simulation, Snapshot } from './types';

interface InitialBody extends Omit<Body, 'sleeping'> {
  velocity: [number, number, number]; angular_velocity: [number, number, number];
  joint: { parent: number; parent_anchor: [number, number, number]; child_anchor: [number, number, number] } | null;
}
export interface InitialScene { fingerprint: string; bodies: InitialBody[]; floor_half_extents: [number, number, number] }
let loading: ReturnType<typeof initJolt> | undefined;

/** Run the official Jolt WebAssembly binding using geometry generated by the Rust core. */
export async function createJoltSimulation(settings: Settings, scene: InitialScene): Promise<Simulation> {
  validateSettings(settings);
  settings = { ...settings }; scene = structuredClone(scene);
  if (settings.dimension !== '3d') throw new Error('Jolt supports only 3D scenes.');
  const J = await (loading ??= initJolt().catch(error => { loading = undefined; throw error; }));
  const pairFilter = new J.ObjectLayerPairFilterTable(2);
  pairFilter.EnableCollision(0, 1); pairFilter.EnableCollision(1, 1);
  const broad = new J.BroadPhaseLayerInterfaceTable(2, 2);
  for (const index of [0, 1]) { const layer = new J.BroadPhaseLayer(index); broad.MapObjectToBroadPhaseLayer(index, layer); J.destroy(layer); }
  const broadFilter = new J.ObjectVsBroadPhaseLayerFilterTable(broad, 2, pairFilter, 2);
  const configuration = new J.JoltSettings();
  configuration.mMaxBodies = Math.max(10240, settings.count + 1);
  configuration.mObjectLayerPairFilter = pairFilter;
  configuration.mBroadPhaseLayerInterface = broad;
  configuration.mObjectVsBroadPhaseLayerFilter = broadFilter;
  const world = new J.JoltInterface(configuration); J.destroy(configuration);
  const system = world.GetPhysicsSystem(), bodies = system.GetBodyInterface();
  const gravity = new J.Vec3(0, -settings.gravity, 0); system.SetGravity(gravity);
  const physicsSettings = new J.PhysicsSettings();
  physicsSettings.mNumVelocitySteps = 10; physicsSettings.mNumPositionSteps = 2;
  system.SetPhysicsSettings(physicsSettings); J.destroy(physicsSettings);
  const owned: object[] = [gravity];
  const bpFilter = new J.DefaultBroadPhaseLayerFilter(world.GetObjectVsBroadPhaseLayerFilter(), 1);
  const objectFilter = new J.DefaultObjectLayerFilter(world.GetObjectLayerPairFilter(), 1);
  const bodyFilter = new J.BodyFilter(), shapeFilter = new J.ShapeFilter();
  owned.push(bpFilter, objectFilter, bodyFilter, shapeFilter);
  const characterCollisions = new J.CharacterVsCharacterCollisionSimple();
  const characterSettings = new J.ExtendedUpdateSettings(); owned.push(characterCollisions, characterSettings);
  const velocity = new J.Vec3(0, 0, 0); owned.push(velocity);
  const rigid: Jolt.Body[] = [];
  const characters: Jolt.CharacterVirtual[] = [];
  const handles: (Jolt.Body | Jolt.CharacterVirtual)[] = [];
  const isCharacter: boolean[] = [];
  const constraints: Jolt.Constraint[] = [];
  let isFreed = false, tick = 0, queryHits = 0;
  const isJointed = scene.bodies.some(body => body.joint !== null);
  const groupSize = settings.scenario === 'ragdolls' ? 6 : 12;
  const groupFilter = new J.GroupFilterTable(groupSize); groupFilter.AddRef();
  for (let index = 0; index < scene.bodies.length; index++) {
    const joint = scene.bodies[index].joint;
    if (joint) groupFilter.DisableCollision(joint.parent % groupSize, index % groupSize);
  }
  const makeShape = (shape: Body['shape']): Jolt.ConvexShape => {
    if (shape.kind === 'ball') { const result = new J.SphereShape(shape.radius); result.SetDensity(1); return result; }
    const extent = new J.Vec3(...shape.half_extents);
    const result = new J.BoxShape(extent, 0); J.destroy(extent); result.SetDensity(1); return result;
  };
  const makeBody = (body: InitialBody, index?: number): Jolt.Body => {
    const shape = makeShape(body.shape);
    const position = new J.RVec3(...body.position), rotation = new J.Quat(...body.rotation);
    const motion = body.kind === 'static' ? J.EMotionType_Static : body.kind === 'dynamic' ? J.EMotionType_Dynamic : J.EMotionType_Kinematic;
    const creation = new J.BodyCreationSettings(shape, position, rotation, motion, body.kind === 'static' ? 0 : 1);
    J.destroy(position); J.destroy(rotation);
    creation.mFriction = settings.friction; creation.mRestitution = settings.restitution;
    creation.mLinearDamping = 0; creation.mAngularDamping = 0;
    creation.mAllowSleeping = settings.sleeping === 'enabled';
    creation.mMotionQuality = settings.ccd === 'continuous' ? J.EMotionQuality_LinearCast : J.EMotionQuality_Discrete;
    creation.mLinearVelocity.Set(...body.velocity); creation.mAngularVelocity.Set(...body.angular_velocity);
    if (index !== undefined && isJointed) {
      const group = new J.CollisionGroup(groupFilter, Math.floor(index / groupSize), index % groupSize);
      creation.mCollisionGroup = group; J.destroy(group);
    }
    const result = bodies.CreateBody(creation); J.destroy(creation);
    if (!J.getPointer(result)) throw new Error('Jolt could not allocate a body. Reduce the body count.');
    bodies.AddBody(result.GetID(), J.EActivation_Activate); rigid.push(result);
    return result;
  };
  const free = () => {
    if (isFreed) return; isFreed = true;
    for (const constraint of constraints) system.RemoveConstraint(constraint);
    for (const character of characters) { characterCollisions.Remove(character); J.destroy(character); }
    for (const body of rigid) { const id = body.GetID(); bodies.RemoveBody(id); bodies.DestroyBody(id); }
    groupFilter.Release();
    for (const object of owned.reverse()) J.destroy(object);
    J.destroy(world);
  };
  try {
    makeBody({ position: [0, -scene.floor_half_extents[1], 0], rotation: [0, 0, 0, 1],
      shape: { kind: 'box', half_extents: scene.floor_half_extents }, kind: 'static', velocity: [0, 0, 0], angular_velocity: [0, 0, 0], joint: null });
    for (const [index, body] of scene.bodies.entries()) {
      const controlled = settings.scenario === 'characters' && body.kind === 'kinematic'; isCharacter.push(controlled);
      if (controlled) {
        const configuration = new J.CharacterVirtualSettings(); configuration.mShape = makeShape(body.shape);
        const position = new J.RVec3(...body.position), rotation = new J.Quat(...body.rotation);
        const character = new J.CharacterVirtual(configuration, position, rotation, system);
        J.destroy(configuration); J.destroy(position); J.destroy(rotation);
        character.SetCharacterVsCharacterCollision(characterCollisions); characterCollisions.Add(character);
        characters.push(character); handles.push(character);
      } else handles.push(makeBody(body, index));
    }
    for (const [index, body] of scene.bodies.entries()) {
      if (!body.joint) continue;
      const configuration = new J.PointConstraintSettings(); configuration.mSpace = J.EConstraintSpace_LocalToBodyCOM;
      configuration.mPoint1.Set(...body.joint.parent_anchor); configuration.mPoint2.Set(...body.joint.child_anchor);
      const constraint = configuration.Create(handles[body.joint.parent] as Jolt.Body, handles[index] as Jolt.Body);
      system.AddConstraint(constraint); constraints.push(constraint); J.destroy(configuration);
    }
    system.OptimizeBroadPhase();
    const ray = new J.RRayCast(), raySettings = new J.RayCastSettings(), collector = new J.CastRayClosestHitCollisionCollector();
    ray.mDirection.Set(0, -1.5, 0); owned.push(ray, raySettings, collector);
    return {
      fingerprint: () => scene.fingerprint,
      advance(steps: number): void {
        if (isFreed) throw new Error('This Jolt world has been released.');
        if (!Number.isInteger(steps) || steps < 1 || steps > 10000) throw new Error('steps must be an integer between 1 and 10000.');
        for (let step = 0; step < steps; step++) {
          const speed = Math.cos((tick + 1) / settings.hz) * 2;
          for (let index = 0; index < handles.length; index++) {
            if (isCharacter[index]) {
              const character = handles[index] as Jolt.CharacterVirtual;
              velocity.Set(speed, -4, 0); character.SetLinearVelocity(velocity);
              character.ExtendedUpdate(1 / settings.hz, gravity, characterSettings, bpFilter, objectFilter, bodyFilter, shapeFilter, world.GetTempAllocator());
            } else if (scene.bodies[index].kind === 'kinematic') {
              velocity.Set(speed, 0, 0); bodies.SetLinearVelocity((handles[index] as Jolt.Body).GetID(), velocity);
            }
          }
          for (let substep = 0; substep < settings.solver_effort; substep++) world.Step(1 / settings.hz / settings.solver_effort, 1);
          tick++;
          if (settings.scenario === 'queries') {
            queryHits = 0;
            for (const [index, body] of scene.bodies.entries()) {
              ray.mOrigin.Set(body.position[0] + (index % 2 ? 1000 : 0), body.position[1] + 1, body.position[2]); collector.Reset();
              system.GetNarrowPhaseQuery().CastRay(ray, raySettings, collector, bpFilter, objectFilter, bodyFilter, shapeFilter);
              if (collector.HadHit()) queryHits++;
            }
          }
        }
      },
      snapshot(): string {
        if (isFreed) throw new Error('This Jolt world has been released.');
        const snapshot: Snapshot = { tick, bodies: handles.map((handle, index) => {
          const position = handle.GetPosition(), rotation = handle.GetRotation();
          return { position: [position.GetX(), position.GetY(), position.GetZ()], rotation: [rotation.GetX(), rotation.GetY(), rotation.GetZ(), rotation.GetW()],
            shape: scene.bodies[index].shape, kind: scene.bodies[index].kind, sleeping: !isCharacter[index] && !(handle as Jolt.Body).IsActive() };
        }), joints: scene.bodies.flatMap((body, index) => body.joint ? [[body.joint.parent, index] as [number, number]] : []) };
        return JSON.stringify({ ...snapshot, queries: { rays: settings.scenario === 'queries' ? scene.bodies.length : 0, hits: queryHits } });
      }, free,
    };
  } catch (error) { free(); throw error; }
}
